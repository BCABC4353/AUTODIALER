const AREA_CODE_TZ = new Map<string, string>();
for (const [tz, codes] of Object.entries(TZ_GROUPS)) {
  for (const code of codes) {
    const key = String(code);
    if (!AREA_CODE_TZ.has(key)) AREA_CODE_TZ.set(key, tz);
  }
}

export const DEFAULT_TZ: string | null = null;
export const FALLBACK_TZ = 'America/Los_Angeles';

export function tzForPhone(digits: string | null | undefined): string | null {
  if (!digits) return null;
  return AREA_CODE_TZ.get(digits.slice(0, 3)) ?? DEFAULT_TZ;
}

export function tzLabel(tz: string | null | undefined): string {
  return (tz || 'unknown').split('/').pop()!.replace(/_/g, ' ');
}
